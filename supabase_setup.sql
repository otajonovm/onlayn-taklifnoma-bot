create table if not exists public.usage_counter (
  id integer primary key default 1,
  tokens bigint not null default 0,
  constraint usage_counter_singleton check (id = 1)
);

insert into public.usage_counter (id, tokens) values (1, 0)
on conflict (id) do nothing;

create or replace function public.add_tokens(amount integer)
returns bigint
language plpgsql
security definer
as $$
declare total bigint;
begin
  insert into public.usage_counter (id, tokens)
  values (1, greatest(amount, 0))
  on conflict (id) do update
    set tokens = public.usage_counter.tokens + greatest(amount, 0)
  returning tokens into total;
  return total;
end;
$$;

grant execute on function public.add_tokens(integer) to anon, authenticated;

