create table if not exists public.templates (
  id bigint generated by default as identity primary key,
  title text not null,
  kind text not null default 'sayt' check (kind in ('video', 'sayt', 'rasm')),
  url text,
  media_url text,
  media_type text check (media_type in ('photo', 'video')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.templates enable row level security;

drop policy if exists "templates_read" on public.templates;
drop policy if exists "templates_insert" on public.templates;
drop policy if exists "templates_update" on public.templates;

create policy "templates_read" on public.templates
  for select to anon, authenticated using (true);
create policy "templates_insert" on public.templates
  for insert to anon, authenticated with check (true);
create policy "templates_update" on public.templates
  for update to anon, authenticated using (true) with check (true);

insert into storage.buckets (id, name, public)
values ('templates', 'templates', true)
on conflict (id) do nothing;

drop policy if exists "templates_media_read" on storage.objects;
drop policy if exists "templates_media_insert" on storage.objects;

create policy "templates_media_read" on storage.objects
  for select to anon, authenticated using (bucket_id = 'templates');
create policy "templates_media_insert" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'templates');

